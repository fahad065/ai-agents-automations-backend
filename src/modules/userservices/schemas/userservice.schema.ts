import { Prop, Schema, SchemaFactory } from '@nestjs/mongoose';
import { Document, Types } from 'mongoose';
import { ApiKeyProvider } from '../../api-keys/schemas/api-key.schema';

// userservices — "what does this customer own" (ai/architecture.md).
// One row per subscribed service. `type` is always a real type, never
// "bundle"; `serviceId` is always one reference, never an array.
//
// Two Mongoose models share this collection:
//   - UserService: the generic row, `config` loose (agents/automations).
//   - ChatbotUserService: the same row with `config` typed for chatbots
//     (channels, branches, AI models…), so defaults and casting work.
// Every chatbot query must include { type: 'chatbot' } (CHATBOT_FILTER).

export enum UserServiceType {
  AGENT = 'agent',
  AUTOMATION = 'automation',
  CHATBOT = 'chatbot',
}

export enum UserServiceStatus {
  TRIAL = 'trial',
  ACTIVE = 'active',
  PAST_DUE = 'past_due',
  SUSPENDED = 'suspended',
  CANCELLED = 'cancelled',
}

export const CHATBOT_FILTER = { type: UserServiceType.CHATBOT } as const;

// The customer's plan for this one service. Prices are per deal (an admin
// can set them by hand); tier drives feature locks (Pro: WhatsApp,
// Instagram, Analytics). Agreed with the owner 2026-11-17.
@Schema({ _id: false })
export class UserServicePlan {
  @Prop({ enum: ['basic', 'pro', 'custom'], default: 'basic' })
  tier: 'basic' | 'pro' | 'custom';

  @Prop({ default: 0 })
  monthlyFee: number;

  @Prop({ default: 0 })
  setupFee: number;

  @Prop({ default: 'USD' })
  currency: string;
}

// Fields every userservices row has, whatever its type.
@Schema({ timestamps: true, collection: 'userservices' })
export class UserServiceBase {
  @Prop({ type: Types.ObjectId, ref: 'User', required: true })
  userId: Types.ObjectId;

  @Prop({ enum: UserServiceType, required: true })
  type: UserServiceType;

  @Prop({ type: Types.ObjectId, ref: 'Service' })
  serviceId?: Types.ObjectId;

  // Grouping label only — set when bought as part of a bundle.
  @Prop({ type: Types.ObjectId })
  bundleId?: Types.ObjectId;

  // The customer's own name for this subscription ("IronFit Marina bot").
  @Prop({ required: true, trim: true })
  name: string;

  @Prop({ enum: UserServiceStatus, default: UserServiceStatus.TRIAL })
  status: UserServiceStatus;

  // An exemption that skips billing, not a lifecycle stage.
  @Prop({ default: false })
  isFreeForever: boolean;

  @Prop({ default: false })
  isDeleted: boolean;

  @Prop({ default: () => new Date() })
  subscriptionStartDate: Date;

  @Prop()
  trialEndDate?: Date;

  @Prop()
  nextRenewalDate?: Date;

  @Prop()
  cancelledAt?: Date;

  @Prop({ type: UserServicePlan, default: () => ({}) })
  plan: UserServicePlan;

  // Admin-only deal notes — never returned to the customer.
  @Prop()
  adminNotes?: string;

  // Set once the "trial ends in 5 days" email went out, so it never repeats.
  @Prop()
  trialReminderSentAt?: Date;
}

@Schema({ timestamps: true, collection: 'userservices' })
export class UserService extends UserServiceBase {
  // Shape depends on the service; validated in the service layer.
  @Prop({ type: Object, default: {} })
  config: Record<string, any>;
}

export type UserServiceDocument = UserService & Document;
export const UserServiceSchema = SchemaFactory.createForClass(UserService);
UserServiceSchema.index({ userId: 1, type: 1, isDeleted: 1 });
UserServiceSchema.index({ status: 1, trialEndDate: 1 });

// ── Chatbot config ───────────────────────────────────────────────

// Which BYOK provider+model this chatbot's chat replies / knowledge-base
// embeddings are generated with. `model: 'auto'` (the default) means "let
// the backend pick a sensible default for whichever provider is chosen" —
// see ai-provider.util.ts's resolveChatModel()/resolveEmbeddingModel().
// Provider here is always explicit (it determines which of the owner's
// BYOK keys actually gets billed); only the specific model within that
// provider defaults to auto. Anthropic is never valid for
// embeddingModelConfig — it has no embeddings API at all (validated in
// ChatbotsService.create()/update(), not at the schema level).
@Schema({ _id: false })
export class AiModelConfig {
  @Prop({ type: String, enum: ApiKeyProvider, default: ApiKeyProvider.OPENAI })
  provider: ApiKeyProvider;

  @Prop({ default: 'auto' })
  model: string;
}

@Schema({ _id: false })
export class WebsiteChannel {
  @Prop({ default: false })
  enabled: boolean;

  @Prop()
  customColor?: string;

  @Prop()
  welcomeMessage?: string;

  @Prop()
  welcomeMessage_ar?: string;
}

@Schema({ _id: false })
export class WhatsappChannel {
  @Prop({ default: false })
  enabled: boolean;

  @Prop()
  phoneNumberId?: string;

  @Prop()
  accessToken?: string;

  // Random per-bot token Meta must echo back in the webhook handshake
  // (generated by ChatbotsService on save; shown in the Channels tab).
  @Prop()
  verifyToken?: string;

  // The client's Meta app secret. Every incoming webhook POST must carry an
  // X-Hub-Signature-256 HMAC of the raw body made with it — anything else
  // is rejected before any AI call (ChatService.verifyMetaSignature()).
  @Prop()
  appSecret?: string;

  @Prop({ default: false })
  webhookVerified: boolean;
}

@Schema({ _id: false })
export class InstagramChannel {
  @Prop({ default: false })
  enabled: boolean;

  @Prop()
  accountId?: string;

  @Prop()
  accessToken?: string;

  // Same as WhatsappChannel: handshake token + app secret for signatures.
  @Prop()
  verifyToken?: string;

  @Prop()
  appSecret?: string;

  @Prop({ default: false })
  webhookVerified: boolean;
}

@Schema({ _id: false })
export class ChatbotChannels {
  @Prop({ type: WebsiteChannel, default: () => ({}) })
  website: WebsiteChannel;

  @Prop({ type: WhatsappChannel, default: () => ({}) })
  whatsapp: WhatsappChannel;

  @Prop({ type: InstagramChannel, default: () => ({}) })
  instagram: InstagramChannel;
}

// A single physical/delivery-coverage location for a multi-branch business
// (e.g. a restaurant chain with outlets across several cities, or even
// countries). Generic on purpose — not tied to any one template or
// customer — so any chatbot with more than one location can use it, not
// just restaurants. `areaTags` exists specifically for delivery-only or
// wide-coverage locations (e.g. a single kitchen that delivers to several
// neighborhoods via Talabat/Noon/etc): a customer asking "do you deliver
// to X" or "which branch is near X" can be answered correctly even when
// X isn't the outlet's own address. See ChatService.buildSystemPrompt(),
// which includes the full outlet list in every reply (not subject to the
// knowledge-base's top-4 similarity ranking) so the model can reason over
// all locations at once rather than possibly missing the relevant one.
@Schema({ _id: true })
export class Outlet {
  @Prop({ required: true })
  name: string;

  @Prop({ required: true })
  city: string;

  @Prop({ required: true })
  country: string;

  @Prop()
  address?: string;

  // Extra area/neighborhood names this outlet serves or is known by —
  // beyond its own city/address — so "near Business Bay" can match a
  // delivery-only kitchen based in Al Quoz, for example.
  @Prop({ type: [String], default: [] })
  areaTags: string[];

  @Prop()
  phone?: string;

  // Free text on purpose — real-world hours ("11am-1am daily", "Fri-Sat
  // until 2am, rest of week until midnight") don't fit a simple schema
  // cleanly, and every other free-text field in this schema (persona,
  // fallbackMessage) already takes the same approach.
  @Prop()
  hours?: string;

  @Prop({ type: [String], default: [] })
  deliveryPlatforms: string[];

  // What this branch offers, labelled per template in the dashboard
  // (gym/hotel: "Facilities", clinic/salon: "Services offered", …).
  @Prop({ type: [String], default: [] })
  facilities: string[];

  @Prop()
  mapUrl?: string;

  @Prop({ default: false })
  isOnlineOnly: boolean;

  @Prop()
  notes?: string;
}
const OutletSchema = SchemaFactory.createForClass(Outlet);

@Schema({ _id: false })
export class ChatbotConfig {
  // Whether the bot answers at all: draft → active (live) → inactive (paused).
  // Separate from the subscription status above.
  @Prop({ enum: ['draft', 'active', 'inactive'], default: 'draft' })
  botStatus: 'draft' | 'active' | 'inactive';

  @Prop()
  description?: string;

  @Prop()
  persona?: string;

  // A link the bot shares when someone wants to book (table, trial class,
  // appointment…). Not a booking integration.
  @Prop()
  bookingUrl?: string;

  @Prop({ enum: ['en', 'ar', 'both'], default: 'both' })
  language: 'en' | 'ar' | 'both';

  @Prop({ default: "I'm not sure about that. Let me connect you with a human." })
  fallbackMessage: string;

  @Prop({ default: 'لست متأكداً من ذلك. دعني أوصلك بأحد المختصين.' })
  fallbackMessage_ar: string;

  @Prop({ default: false })
  humanHandoff: boolean;

  // Public key the website widget and Meta webhooks use (/chat/<embedKey>).
  @Prop({ required: true })
  embedKey: string;

  @Prop({ type: ChatbotChannels, default: () => ({}) })
  channels: ChatbotChannels;

  // Empty for a single-location business.
  @Prop({ type: [OutletSchema], default: [] })
  outlets: Outlet[];

  @Prop({ type: AiModelConfig, default: () => ({}) })
  chatModelConfig: AiModelConfig;

  @Prop({ type: AiModelConfig, default: () => ({}) })
  embeddingModelConfig: AiModelConfig;
}

@Schema({ timestamps: true, collection: 'userservices' })
export class ChatbotUserService extends UserServiceBase {
  @Prop({ type: ChatbotConfig, default: () => ({}) })
  config: ChatbotConfig;
}

export type ChatbotUserServiceDocument = ChatbotUserService & Document;
export const ChatbotUserServiceSchema = SchemaFactory.createForClass(ChatbotUserService);
ChatbotUserServiceSchema.index(
  { 'config.embedKey': 1 },
  { unique: true, partialFilterExpression: { 'config.embedKey': { $type: 'string' } } },
);
